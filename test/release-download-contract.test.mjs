import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
test('generic release downloads never silently select ARM64', () => {
  const latest=read('src/app/latest/route.ts'), workflow=read('src/release-workflow.mjs'), download=read('src/app/download/omy-play/DownloadButtons.tsx')
  assert.match(latest,/DOWNLOAD_PAGE = 'https:\/\/otya\.site\/download\/omy-play'/)
  assert.match(latest,/auto:\s+DOWNLOAD_PAGE/)
  assert.doesNotMatch(latest,/auto:\s+ARM64_APK/)
  assert.match(workflow,/download\/omy-play/)
  assert.match(workflow,/apk\/arm64/)
  assert.match(workflow,/apk\/arm32/)
  assert.match(download,/abi:'unknown'/)
  assert.match(download,/Choose your Android build/)
  assert.match(download,/Omy Play will not guess/)
  assert.match(download,/download\('arm64'\)/)
  assert.match(download,/download\('arm32'\)/)
  assert.doesNotMatch(download,/\/android\/i\.test\(ua\) \? 'arm64' : 'unknown'/)
})
test('release workflow binds immutable build tags to the public version and Android version code', () => {
  const source=read('src/release-workflow.mjs')
  assert.match(source,/const TAG_RE/)
  assert.match(source,/tagVersion !== version/)
  assert.match(source,/tagBuild !== versionCode/)
  assert.match(source,/tag build and versionCode do not match/)
  assert.doesNotMatch(source,/tag !==/)
})
test('exact APK requests use immutable paths and fail closed when the exact APK is missing', () => {
  const route=read('src/app/apk/[file]/route.ts')
  assert.match(route,/BUILD_TAG_RE/)
  assert.match(route,/searchParams\.get\('tag'\)/)
  assert.match(route,/searchParams\.get\('v'\)/)
  assert.match(route,/Choose either tag or version, not both/)
  assert.match(route,/if \(tag \|\| version\)/)
  assert.match(route,/Requested release APK not found\./)
  assert.match(route,/status: 404/)
  assert.match(route,/download\/omy-play/)
})
test('APK routes force Android package MIME instead of trusting R2 metadata', () => {
  const route=read('src/app/apk/[file]/route.ts')
  assert.match(route,/APK_CONTENT_TYPE = 'application\/vnd\.android\.package-archive'/)
  assert.match(route,/headers\.set\('Content-Type', APK_CONTENT_TYPE\)/)
  assert.match(route,/headers\.set\('X-Content-Type-Options', 'nosniff'\)/)
  assert.doesNotMatch(route,/object\.httpMetadata\?\.contentType \?\?/)
})
test('release metadata keeps the canonical Otya APK aliases and immutable exact URLs', () => {
  const source=read('src/release-workflow.mjs')
  assert.match(source,/tag: release\.tag/)
  assert.match(source,/arm64: 'Otya-arm64\.apk'/)
  assert.match(source,/arm32: 'Otya-arm32\.apk'/)
  assert.match(source,/exactArm64: immutableApkUrl/)
  assert.match(source,/exactArm32: immutableApkUrl/)
  assert.doesNotMatch(source,/OtyaPlayer-arm64\.apk|OtyaPlayer-arm32\.apk/)
})
test('a different release tag cannot reuse or decrease the Android version code', () => {
  const source=read('src/release-workflow.mjs')
  assert.match(source,/latest\.tag !== release\.tag/)
  assert.match(source,/Number\(latest\.version_code\) >= release\.versionCode/)
  assert.match(source,/Refusing non-monotonic version code/)
})
test('optional reporting cannot turn an already-published release into a false failure', () => {
  const source=read('src/release-workflow.mjs')
  assert.match(source,/Completion report failed/)
  assert.match(source,/Analytics write failed/)
  assert.match(source,/Push notification queue failed/)
  assert.match(source,/return \{ sent: false, error:/)
  assert.match(source,/return \{ written: false, error:/)
  assert.match(source,/queued: false,[\s\S]*?duplicate: false,[\s\S]*?error:/)
})
