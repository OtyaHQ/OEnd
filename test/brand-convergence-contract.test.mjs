import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
test('admin assistant uses the approved Otya identity while generic loading stays quiet', () => {
  const mark=read('src/components/OtyaBrandMark.tsx'), ui=read('src/app/admin/ai/ConsoleClient.tsx'), loading=read('src/app/loading.tsx'), css=read('src/app/brand-overrides.css')
  assert.match(mark,/ai\?: boolean/)
  assert.match(mark,/Otya assistant/)
  assert.match(mark,/src="\/otya-app-icon\.webp"/)
  assert.match(mark,/thinking \? 'otya-brand-thinking' : ''/)
  assert.doesNotMatch(mark,/otya-ai-thinking\.svg|otya-ai\.svg|otya-icon\.svg|otya-icon-dark\.svg/)
  assert.match(ui,/<OtyaBrandMark ai/)
  assert.match(ui,/<OtyaBrandMark ai[^>]*thinking/)
  assert.match(ui,/What should O handle\?/)
  assert.doesNotMatch(ui,/Otya Next|OTYA NEXT/)
  assert.match(loading,/>Loading<\/span>/)
  assert.match(loading,/animate-pulse/)
  assert.doesNotMatch(loading,/OtyaBrandMark|Loading Omy Play/)
  assert.match(css,/@keyframes otya-brand-thinking/)
  assert.match(css,/prefers-reduced-motion: reduce/)
})
test('website metadata and visual tokens match the approved Otya brand', () => {
  const layout=read('src/app/layout.tsx'), css=read('src/app/brand-overrides.css'), manifest=read('public/manifest.json'), webmanifest=read('public/site.webmanifest'), sync=read('scripts/sync-brand-assets.mjs'), download=read('src/app/download/omy-play/DownloadButtons.tsx')
  assert.doesNotMatch(layout,/const APP_VERSION =|softwareVersion:/)
  assert.match(layout,/const OTYA_MARK = '\/otya-app-icon\.webp'/)
  assert.match(layout,/brand-overrides\.css/)
  assert.match(layout,/#050812/)
  for(const token of ['--otya-cyan: #27E8FF','--otya-blue: #126BFF','--otya-deep-blue: #173BFF','--otya-near-black: #050812','--otya-surface: #0A1020']) assert.ok(css.includes(token),token)
  assert.match(manifest,/otya-app-icon\.webp/)
  assert.match(webmanifest,/otya-app-icon\.webp/)
  assert.match(download,/src="\/otya-app-icon\.webp"/)
  assert.match(sync,/EXPECTED_SHA256|APPROVED_APP_COMMIT/)
  assert.match(sync,/EXPECTED_WIDTH = 512/)
  assert.match(sync,/EXPECTED_HEIGHT = 512/)
  assert.doesNotMatch(css,/--otya-red:|--otya-yellow:|--otya-blue: #2979FF/i)
})
